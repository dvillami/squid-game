create table if not exists public.game_videos (
 id bigint generated by default as identity primary key,
 name text not null,
 description text not null default '',
 game_name text not null default '',
 category text not null default 'instrucciones' check (category in ('instrucciones','musica','ambiente')),
 youtube_url text not null,
 is_active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.video_playback (
 id integer primary key default 1 check (id=1),
 video_id bigint references public.game_videos(id) on delete set null,
 action text not null default 'stop' check(action in ('play','pause','stop')),
 revision bigint not null default 0,
 updated_at timestamptz not null default now()
);
insert into public.video_playback(id) values (1) on conflict(id) do nothing;
create or replace function public.is_video_admin() returns boolean language sql stable security definer set search_path = public as $$
 select exists(select 1 from public.admin_users where user_id = (select auth.uid()));
$$;
revoke all on function public.is_video_admin() from public;
grant execute on function public.is_video_admin() to authenticated;
grant select,insert,update,delete on public.game_videos to authenticated;
grant select,insert,update,delete on public.video_playback to authenticated;
grant usage,select on sequence public.game_videos_id_seq to authenticated;
alter table public.game_videos enable row level security;
alter table public.video_playback enable row level security;
drop policy if exists video_catalog_admin on public.game_videos;
create policy video_catalog_admin on public.game_videos for all to authenticated using (public.is_video_admin()) with check (public.is_video_admin());
drop policy if exists video_playback_admin on public.video_playback;
create policy video_playback_admin on public.video_playback for all to authenticated using (public.is_video_admin()) with check (public.is_video_admin());
-- Solo administradores pueden ver y controlar los videos.
create or replace function public.control_video(p_video_id bigint, p_action text)
returns public.video_playback language plpgsql security invoker as $$
declare result public.video_playback;
begin
 if not public.is_video_admin() then raise exception 'No autorizado'; end if;
 if p_action not in ('play','pause','stop') then raise exception 'Acción no válida'; end if;
 if p_action='play' and not exists(select 1 from public.game_videos where id=p_video_id and is_active) then raise exception 'Video no disponible'; end if;
 update public.video_playback set video_id=case when p_action='stop' then null when p_action='play' then p_video_id else video_id end,
 action=p_action, revision=revision+1,updated_at=now() where id=1 returning * into result;
 return result;
end;
$$;
grant execute on function public.control_video(bigint,text) to authenticated;
